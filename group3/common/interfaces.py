from pathlib import Path
from typing import Protocol

from .schemas import PaperDocument, PaperMetadata, RetrievalResult


class SearchProvider(Protocol):
    async def search(self, topic: str, limit: int) -> list[PaperMetadata]: ...


class Ranker(Protocol):
    def rank(self, topic: str, papers: list[PaperMetadata]) -> list[PaperMetadata]: ...


class PaperStore(Protocol):
    def begin(self, task_id: str, run_id: str) -> Path: ...
    def save(self, folder: Path, paper: PaperDocument) -> None: ...
    def finish(self, folder: Path, result: RetrievalResult) -> None: ...
    def load(self, folder: Path, paper_id: str) -> PaperDocument: ...
    def list_papers(self, folder: Path) -> list[PaperDocument]: ...


class DocumentFetcher(Protocol):
    async def fetch(self, paper: PaperMetadata, folder: Path) -> PaperDocument: ...
